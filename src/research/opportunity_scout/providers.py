from urllib.request import build_opener, HTTPRedirectHandler, ProxyHandler, Request

from src.research.spec import canonical, digest
from . import schema as S

JEV_ENDPOINT = 'https://api.typesafe.ai/v1/systemone'
JEV_MODEL = 'jev-1.13.0'
OLLAMA_ENDPOINT = 'http://127.0.0.1:11434/api/generate'
UNKNOWN_USAGE = {'input_tokens': S.UNKNOWN, 'output_tokens': S.UNKNOWN, 'cost': S.UNKNOWN, 'currency': S.UNKNOWN}


class NoRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        raise S.ScoutError('provider redirects are refused; no retry or credential forwarding')


def post_json(endpoint, payload, headers=None):
    if endpoint not in (OLLAMA_ENDPOINT, JEV_ENDPOINT): raise S.ScoutError('unapproved provider endpoint')
    body = canonical(payload)
    if len(body) > 180000: raise S.ScoutError('provider payload exceeds 180 kB')
    request = Request(endpoint, data=body, headers={'Content-Type': 'application/json', **(headers or {})}, method='POST')
    opener = build_opener(ProxyHandler({}), NoRedirect())
    with opener.open(request, timeout=60) as response:
        raw = response.read(1_000_001)
        if len(raw) > 1_000_000: raise S.ScoutError('provider response exceeds 1 MB')
        return S.json_loads(raw.decode('utf-8')), raw.decode('utf-8')


class OllamaProvider:
    """A configured local model, not a hosted fallback. Never pulls/downloads a model."""
    def __init__(self, model, transport=post_json):
        if not model or len(model) > 200: raise S.ScoutError('a local model identity is required')
        self.model, self.transport = model, transport

    def generate(self, prompt, seed=0):
        started = S.utc_now()
        payload = {'model': self.model, 'prompt': canonical(prompt).decode(), 'stream': False,
                   'format': prompt['response_schema'],
                   'options': {'seed': seed, 'temperature': .8, 'num_predict': prompt['max_output_tokens']}}
        response, raw = self.transport(OLLAMA_ENDPOINT, payload)
        if response.get('done') is not True or not isinstance(response.get('response'), str):
            raise S.ScoutError('local model returned an incomplete or invalid response')
        provenance = {'model': response.get('model', self.model), 'provider': 'OLLAMA_LOCAL',
            'invoked_at': started, 'completed_at': S.utc_now(), 'parameters': payload['options'], 'seed': seed,
            'usage': {**UNKNOWN_USAGE, 'input_tokens': response.get('prompt_eval_count', S.UNKNOWN),
                      'output_tokens': response.get('eval_count', S.UNKNOWN)},
            'context_declaration': 'Fresh stateless request; only the frozen prompt was supplied.', 'operator': 'LOCAL_CLI'}
        return response['response'], provenance, raw


QUESTIONS = {
    'explicit_mechanism': 'Does the card state a concrete economic causal mechanism rather than a broad theme?',
    'evidence_supported': 'Do the supplied exact source passages support the factual premises claimed as documented? If no direct evidence is supplied, choose unsure rather than rejecting the speculative idea.',
    'falsifiable': 'Does the card identify a concrete observation that could weaken its economic mechanism?',
    'next_check_addresses_gap': 'Would the proposed next research question directly address the stated main uncertainty?',
    'certainty_exceeds_evidence': 'Does the card assert a relationship, allocation, timing or financial exposure more strongly than its supplied evidence supports?',
}


def shadow_request(state, idea_id):
    card = state.latest(idea_id)
    return {'model': JEV_MODEL, 'state': {'card': card['idea'],
        'seeds': [{'id': sid, 'text': state.seeds[sid]['text'][:8000], 'depth': state.seeds[sid]['depth'],
                   'limitations': state.seeds[sid]['limitations']} for sid in card['idea']['seed_ids']],
        'policy': 'Shadow judgments only. A coherent unverified idea remains eligible for incubation. No alpha, M/H or routing decision.'},
        'questions': {qid: {'type': 'choice', 'instructions': instruction,
            'criteria': {'yes': 'Supported by the supplied content.', 'no': 'Not supported by the supplied content.',
                         'unsure': 'Insufficient or ambiguous supplied information.'}} for qid, instruction in QUESTIONS.items()}}


class JevShadowClient:
    """Future opt-in only. This task sends no hosted request or unpublished research."""
    def __init__(self, transport=post_json): self.transport = transport

    def call(self, payload, *, approval=None, key=None):
        # Approval is an owner-supplied, payload-specific record, not generated by this tool.
        if not approval or approval.get('payload_sha256') != digest(payload) or approval.get('owner_approved') is not True:
            raise S.ScoutError('hosted Jev needs separate owner approval for this exact payload and cost')
        if approval.get('classification') not in ('PUBLIC_APPROVED', 'SYNTHETIC_APPROVED') or not approval.get('authority_reference'):
            raise S.ScoutError('private or unpublished material cannot be sent without explicit separate authority')
        key = key or os.environ.get('TYPESAFE_API_KEY')
        if not key: raise S.ScoutError('Jev key unavailable; use shadow request/response import instead')
        return self.transport(JEV_ENDPOINT, payload, {'Authorization': 'Bearer ' + key})


def validate_shadow(state, record):
    from .engine import require_card
    S.validate(S.obj({'idea_id': S.LABEL, 'version': {'type': 'integer', 'minimum': 1},
        'request_sha256': S.HASH, 'response': {'type': 'object'}, 'imported_at': S.TEXT,
        'cost': S.NUMBER, 'currency': S.enum(('USD', S.UNKNOWN)), 'shadow_only': {'const': True},
        'transport': S.enum(('IMPORTED_NOT_CALLED', 'SYNTHETIC_FIXTURE', 'OWNER_AUTHORISED_HTTP'))}), record)
    card = require_card(state, record)
    if record['request_sha256'] != digest(shadow_request(state, card['id'])): raise S.ScoutError('shadow request hash mismatch')
    if record['transport'] == 'SYNTHETIC_FIXTURE' and state.batch['fixture'] != 'SYNTHETIC': raise S.ScoutError('synthetic shadow response in real batch')
    if record['transport'] == 'OWNER_AUTHORISED_HTTP': raise S.ScoutError('hosted dispatch is outside the offline CLI; import a separately authorised response')
    S.timestamp(record['imported_at'])
    response = record['response']
    S.validate(S.obj({'model': S.LABEL, 'answers': {'type': 'object'},
        'usage': S.obj({'input_tokens': {'type': 'integer', 'minimum': 0}, 'output_tokens': {'type': 'integer', 'minimum': 0}})}), response)
    if set(response['answers']) != set(QUESTIONS): raise S.ScoutError('shadow response questions do not match the frozen atomic questions')
    for answer in response['answers'].values():
        S.validate(S.obj({'type': {'const': 'choice'}, 'choice': S.enum(('yes', 'no', 'unsure')),
            'probabilities': S.obj({x: {'type': 'number', 'minimum': 0, 'maximum': 1} for x in ('yes', 'no', 'unsure')}),
            'confidence': {'type': 'number', 'minimum': 0, 'maximum': 1}}), answer)
        if abs(sum(answer['probabilities'].values()) - 1) > 1e-5: raise S.ScoutError('invalid probability distribution')
        if answer['probabilities'][answer['choice']] < max(answer['probabilities'].values()) - 1e-6:
            raise S.ScoutError('choice is inconsistent with the probability distribution')
